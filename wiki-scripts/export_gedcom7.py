GIVEN_OK = re.compile(r"^[^\W\d_][^\d\[\]()/,;:]*$")


def given_name(row):
    """The given part of a person's name, or "" when it cannot be told apart from the rest.

    Only two sources are trusted: the part before the /surname/ in the gedcom column, and a label
    that is a single word. A full label ("Gwyn ap Peredur ab Ednowain", "[66] Pangeran Adipati ...")
    is skipped rather than guessed at, since a wrong given name on every lineage name would be worse
    than none (checked on a sample, 2026-10-15).
    """
    ged = clean_name(row.get("gedcom") or "")
    if "/" in ged:
        g = ged.split("/", 1)[0].strip()
        if g and len(g.split()) <= 2 and GIVEN_OK.match(g):
            return g
    label = clean_name(row.get("label") or "")
    if label and " " not in label and GIVEN_OK.match(label):
        return label
    return ""


PAGE_NAME = {}   # qid -> the name its /gaiad/characters/ page is built from


def load_gaiad_citations():
    """qid -> [(chapter, stanza, line)] from the rebuilt Gaiad/genealogy files (one person per file)."""
    import json
    gen = Path(__file__).resolve().parent.parent / "Gaiad" / "genealogy"
    out = {}
    for f in gen.glob("*.json"):
        try:
            d = json.loads(f.read_text(encoding="utf-8"))
        except Exception:
            continue
        q = d.get("qid")
        if not q:
            continue
        PAGE_NAME.setdefault(q, d.get("name"))
        seen = out.setdefault(q, [])
        for c in d.get("citations", []):
            t = (c["chapter"], c["stanza"], c["line"])
            if t not in seen:
                seen.append(t)
    for q in out:
        out[q].sort()
    return out


def load_readings():
    """token -> (ja, zh, ko), curated rows winning over rule-minted ones (as genealogy's build-garborg-day.py reads it)."""
    import csv
    path = Path(__file__).resolve().parent.parent / "wikibase" / "analysis" / "name_readings.tsv"
    out, minted = {}, set()
    if path.exists():
        with open(path, encoding="utf-8", newline="") as fh:
            for r in csv.DictReader(fh, delimiter="\t"):
                t, by_rule = r["token"], (r.get("note") or "").startswith("by rule")
                if t in out and t not in minted and by_rule:
                    continue
                out[t] = (r["ja"], r["zh"], r.get("ko", ""))
                (minted.add if by_rule else minted.discard)(t)
    return out


def graft_synoptic(persons, parents_of, mode="emma"):
    """Add the synoptic tree's ancestry (scripts/build_synoptic_supplement.py in the parent repo; Emma, 2026-10-15:
    gaiad.ged from the synoptic tree, her real parents included). The Gaiad's parentage was kept by the builder;
    here the tables are merged: new people as S<cluster>, their edges, and Emma's placeholder edges dropped.

    mode "full": every grafted ancestor (about 42,000 people; with them the file is near GitHub's 100 MB limit, so
    it goes inside the zips only). mode "emma": only Emma's own ancestry and her parents' other children, for the
    main /gaiad.ged. mode None: no graft."""
    if not mode:
        return 0
    import csv
    ana = Path(__file__).resolve().parent.parent / "wikibase" / "analysis"
    if not (ana / "synoptic_persons.tsv").exists():
        return 0
    with open(ana / "synoptic_persons.tsv", encoding="utf-8", newline="") as fh:
        for r in csv.DictReader(fh, delimiter="\t"):
            persons[r["sid"]] = {"qid": r["sid"], "label": r["name"],
                                 "sex": {"M": SEX_MALE, "F": SEX_FEMALE}.get(r["sex"], ""),
                                 "birth": r["birth"], "death": r["death"], "gedcom": "",
                                 "wikidata_qid": r["wikidata"], "geni_id": r["geni"],
                                 "_fs": r["familysearch"], "_synoptic": True}
    with open(ana / "synoptic_drop.tsv", encoding="utf-8", newline="") as fh:
        for r in csv.DictReader(fh, delimiter="\t"):
            if r["parent"] in parents_of.get(r["child"], []):
                parents_of[r["child"]].remove(r["parent"])
    with open(ana / "synoptic_edges.tsv", encoding="utf-8", newline="") as fh:
        edges = [(r["parent"], r["child"]) for r in csv.DictReader(fh, delimiter="\t")]
    if mode == "emma":
        up = {}
        for p, c in edges:
            up.setdefault(c, []).append(p)
        keep, frontier = set(), ["Q2"]
        while frontier:                      # her ancestry, upward through the grafted edges
            nxt = []
            for c in frontier:
                for p in up.get(c, []):
                    if p not in keep:
                        keep.add(p)
                        nxt.append(p)
            frontier = nxt
        her_parents = set(up.get("Q2", []))
        keep |= {c for p, c in edges if p in her_parents}   # her siblings
        keep.add("Q2")
        edges = [(p, c) for p, c in edges if c in keep and p in keep]
        for sid in [k for k, v in persons.items() if v.get("_synoptic") and k not in keep]:
            del persons[sid]
    n = 0
    for p, c in edges:
        if p in persons and c in persons and p not in parents_of.setdefault(c, []):
            parents_of[c].append(p)
            n += 1
    return n


