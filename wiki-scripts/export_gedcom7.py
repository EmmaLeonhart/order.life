ORDERLIFE_QID_URI = "https://order.life/wikibase/entity/"
# Languages whose labels go into the main file as TRAN (name schema: zh, ja, ko beside English); labels.tsv
# may hold others (ar, ru) for the lineage names in those scripts.
PRIMARY_LANGS = ("zh", "ja", "ko")
WIKIDATA_URI = "http://www.wikidata.org/entity/"
# Fixed namespace: the UID of a person is uuid5(UID_NAMESPACE, their order.life QID) forever.
UID_NAMESPACE = uuid.uuid5(uuid.NAMESPACE_URL, "https://order.life/gaiad/person/")

CJK_RE = re.compile(r"[぀-ヿ]")          # kana: Japanese
HAN_RE = re.compile(r"[一-鿿]")
HANGUL_RE = re.compile(r"[가-힯]")
CYRILLIC_RE = re.compile(r"[Ѐ-ӿ]")
ARABIC_RE = re.compile(r"[؀-ۿ]")
DEVANAGARI_RE = re.compile(r"[ऀ-ॿ]")
GREEK_RE = re.compile(r"[Ͱ-Ͽ]")


def lang_of(name):
    """A BCP 47 tag for a name written in a non-Latin script, or None for Latin script."""
    if CJK_RE.search(name):
        return "ja"
    if HANGUL_RE.search(name):
        return "ko"
    if HAN_RE.search(name):
        return "zh"
    if CYRILLIC_RE.search(name):
        return "ru"
    if ARABIC_RE.search(name):
        return "ar"
    if DEVANAGARI_RE.search(name):
        return "hi"
    if GREEK_RE.search(name):
        return "el"
    return None


def val(text):
    """GEDCOM 7 doubles an @ only at the start of a line value."""
    text = " ".join((text or "").split())
    return "@" + text if text.startswith("@") else text


def ged7_date(raw, precision=None):
    """Wikidata-style timestamp -> a GEDCOM 7 DATE. GEDCOM 7 years are unbounded integers, so
    deep time (Aster's -13000000000) is representable as '13000000000 BCE'."""
    if not raw:
        return None
    s = raw.strip()
    neg = s.startswith("-")
    if s[0] in "+-":
        s = s[1:]
    bits = s.split("T", 1)[0].split("-")
    if not bits or not bits[0].isdigit():
        return None
    year = int(bits[0])
    if year == 0:
        return None
    month = int(bits[1]) if len(bits) > 1 and bits[1].isdigit() else 0
    day = int(bits[2]) if len(bits) > 2 and bits[2].isdigit() else 0
    try:
        prec = int(precision) if precision not in (None, "") else 11
    except (TypeError, ValueError):
        prec = 11
    if prec < 10:
        month = day = 0
    elif prec == 10:
        day = 0
    out = []
    if 1 <= month <= 12:
        if 1 <= day <= 31:
            out.append(str(day))
        out.append(MONTHS[month - 1])
    out.append(str(year))
    if neg:
        out.append("BCE")
    date = " ".join(out)
    return f"ABT {date}" if prec <= 8 else date


def other_calendars(raw, precision=None):
    """For an exact date (day precision), its Gaian, Hebrew, Islamic and solar Hijri dates (calendars.py)."""
    try:
        prec = int(precision) if precision not in (None, "") else 11
    except (TypeError, ValueError):
        prec = 11
    if prec < 11:
        return None
    s = raw.strip()
    neg = s.startswith("-")
    bits = s.lstrip("+-").split("T", 1)[0].split("-")
    if len(bits) < 3 or not all(x.isdigit() for x in bits[:3]):
        return None
    y, m, d = int(bits[0]), int(bits[1]), int(bits[2])
    if y == 0 or not (1 <= m <= 12 and 1 <= d <= 31):
        return None
    from calendars import calendar_note
    return calendar_note(1 - y if neg else y, m, d)   # BCE year n is astronomical 1 - n


def person_uid(qid):
    return str(uuid.uuid5(UID_NAMESPACE, qid))


GIVEN_OK = re.compile(r"^[^\W\d_][^\d\[\]()/,;:]*$")


def given_name(row):
    """The given part of a person's name, or "" when it cannot be told apart from the rest.

    Only two sources are trusted: the part before the /surname/ in the gedcom column, and a label
    that is a single word. A full label ("Gwyn ap Peredur ab Ednowain", "[66] Pangeran Adipati ...")
    is skipped rather than guessed at, since a wrong given name on every lineage name would be worse
    than none (checked on a sample, 2026-10-15).
    """
    ged = clean_name(row.get("gedcom") or "")
    if "/" in ged:
        g = ged.split("/", 1)[0].strip()
        if g and len(g.split()) <= 2 and GIVEN_OK.match(g):
            return g
    label = clean_name(row.get("label") or "")
    if label and " " not in label and GIVEN_OK.match(label):
        return label
    return ""


PAGE_NAME = {}   # qid -> the name its /gaiad/characters/ page is built from


def load_gaiad_citations():
    """qid -> [(chapter, stanza, line)] from the rebuilt Gaiad/genealogy files (one person per file)."""
    import json
    gen = Path(__file__).resolve().parent.parent / "Gaiad" / "genealogy"
    out = {}
    for f in gen.glob("*.json"):
        try:
            d = json.loads(f.read_text(encoding="utf-8"))
        except Exception:
            continue
        q = d.get("qid")
        if not q:
            continue
        PAGE_NAME.setdefault(q, d.get("name"))
        seen = out.setdefault(q, [])
        for c in d.get("citations", []):
            t = (c["chapter"], c["stanza"], c["line"])
            if t not in seen:
                seen.append(t)
    for q in out:
        out[q].sort()
    return out


def load_canonical_line():
    """qid -> (canonical parent qid, 'father'|'mother'), from canonical_line.py's output."""
    path = Path(__file__).resolve().parent.parent / "wikibase" / "analysis" / "canonical_line.tsv"
    out = {}
    if path.exists():
        import csv
        with open(path, encoding="utf-8", newline="") as fh:
            for r in csv.DictReader(fh, delimiter="\t"):
                if r["canonical_parent"] and r["link"] in ("father", "mother"):
                    out[r["qid"]] = (r["canonical_parent"], r["link"])
    return out


def lineage_names(qid, persons, sex_of, canon):
    """The name schema's patronymic or matronymic (planning/name-schema.md), in the two forms
    Emma gave: English "Emma Helen's daughter" and Arabic "Emma bint Helen"."""
    if qid not in canon:
        return []
    parent, link = canon[qid]
    child_g, parent_g = given_name(persons[qid]), given_name(persons.get(parent, {}))
    if not child_g or not parent_g or parent_g.lower() in ("father", "mother"):
        return []
    # These two forms are Latin-script patterns; names in other scripts get their own forms
    # (Chinese, Japanese, Arabic script) in later steps of the schema.
    import unicodedata
    if any(ch.isalpha() and not unicodedata.name(ch, "").startswith("LATIN")
           for ch in unicodedata.normalize("NFD", child_g + parent_g)):
        return []
    kind = "patronymic" if link == "father" else "matronymic"
    rel = {"M": "son", "F": "daughter"}.get(sex_of.get(qid), "child")
    arabic = {"M": "ibn", "F": "bint"}.get(sex_of.get(qid), "ibn")
    return [(f"{child_g} {parent_g}'s {rel}", f"{kind}, English form"),
            (f"{child_g} {arabic} {parent_g}", f"{kind}, Arabic form")]

WELSH = re.compile(r"\b(ap|ab|ferch|verch)\s+(\S+)", re.I)
RECORDED_PATRONYMIC = re.compile(r"\b(ap|ab|ferch|verch|ibn|bin|bint)\s+(\S+)", re.I)


def russian_patronymic(parent_given, sex):
    """A Russian patronymic from a parent's Russian given name, by the usual endings: -ович/-овна after a
    consonant, -евич/-евна for -й/-ь, -ич/-ична for -а/-я (Илья -> Ильич). An approximation, marked as such."""
    n = parent_given
    if not n or not re.fullmatch(r"[А-Яа-яЁё-]+", n):
        return ""
    if n[-1] in "йь":
        stem, m, f = n[:-1], "евич", "евна"
    elif n[-1] in "ая":
        stem, m, f = n[:-1], "ич", "ична"
    elif n[-1] in "еиоуыэю":
        stem, m, f = n, "вич", "вна"
    else:
        stem, m, f = n, "ович", "овна"
    return stem + (f if sex == "F" else m)


def lineage_extras(qid, persons, sex_of, canon, labels):
    """Name-schema step 2, later work (planning/name-schema.md): Welsh stacking where the record is Welsh-styled,
    Arabic-script and Russian forms where both person and parent have real labels in those languages, and a NOTE
    where the record's own patronymic differs from the canonical line. Returns (names, notes)."""
    names, notes = [], []
    if qid not in canon:
        return names, notes
    parent, link = canon[qid]
    kind = "patronymic" if link == "father" else "matronymic"
    sex = sex_of.get(qid)
    label = persons[qid].get("label") or ""
    def given(row):
        # Welsh-styled labels carry no separate given name: it is the word before the first ap/ferch.
        g = given_name(row)
        m = WELSH.search(row.get("label") or "")
        if not g and m:
            head = (row.get("label") or "")[:m.start()].strip()
            if head and " " not in head:
                g = head
        return g
    child_g, parent_g = given(persons[qid]), given(persons.get(parent, {}))
    if child_g and parent_g and parent_g.lower() not in ("father", "mother"):
        if WELSH.search(label):
            chain, cur, word = [child_g], parent, ("ferch" if sex == "F" else "ap")
            for _ in range(2):
                g = given(persons.get(cur, {}))
                if not g:
                    break
                if word == "ap" and g[0].lower() in "aeiouyâêîôûŵŷ":
                    word = "ab"  # Welsh writes ab before a vowel (ab Einion)
                chain.append(f"{word} {g}")
                word = "ap" if sex_of.get(cur) == "M" else "ferch"
                if cur not in canon:
                    break
                cur = canon[cur][0]
            if len(chain) > 2:
                names.append((" ".join(chain), f"{kind}, Welsh stacked form"))
        m = RECORDED_PATRONYMIC.search(label)
        if m and m.group(2).strip(",.").lower() != parent_g.split()[0].lower():
            notes.append(f"Recorded patronymic \"{m.group(0)}\"; by the canonical line to Aster and Andromeda, "
                         f"{child_g} is {parent_g}'s {'daughter' if sex == 'F' else 'son'}.")
    lab = dict(labels.get(qid, []))
    plab = dict(labels.get(parent, []))
    if lab.get("ar") and plab.get("ar"):
        word = "بنت" if sex == "F" else "بن"
        names.append((f"{lab['ar'].split()[0]} {word} {plab['ar'].split()[0]}", f"{kind}, Arabic script"))
    # Russian form only where the person's own Russian label already carries a patronymic, so it is used
    # for people named in the Russian way, not imposed on a Japanese or Persian name.
    ru_has_pat = bool(lab.get("ru")) and bool(re.search(r"\S+(ович|евич|ич|овна|евна|ична|инична)\b", lab.get("ru", "")[len(lab.get("ru", "").split()[0]):]))
    first_ru = lab.get("ru", " ").split()[0] if lab.get("ru") else ""
    if first_ru.endswith(("ович", "евич", "овна", "евна", "ична")):
        ru_has_pat = False  # the record's first name is itself a patronymic (Igorevich Yaroslavich)
    if ru_has_pat and plab.get("ru"):
        pat = russian_patronymic(plab["ru"].split()[0], sex) if link == "father" else ""
        if pat:
            names.append((f"{lab['ru'].split()[0]} {pat}", f"{kind}, Russian form (approximate)"))
    return names, notes


def build_gedcom7(out_path, extra_lang=None):
    """extra_lang: a language directory's own language (Emma, 2026-10-14: the other language versions "only
    contain English, Japanese, Chinese, and then whatever ... other language the directory is in"); its real
    labels are added beside the primary zh, ja and ko."""
    tran_langs = PRIMARY_LANGS + ((extra_lang,) if extra_lang and extra_lang not in PRIMARY_LANGS else ())
    persons, parents_of, spouse_pairs, precision = load()

    sex_of = {}
    for qid, row in persons.items():
        raw = row.get("sex") or ""
        sex_of[qid] = "M" if raw == SEX_MALE else "F" if raw == SEX_FEMALE else "U"

    fam_children = defaultdict(set)
    for child, parents in parents_of.items():
        for key in couples_for_child(parents, sex_of, spouse_pairs):
            fam_children[key].add(child)
    for pair in spouse_pairs:
        a, b = sorted(pair)
        if sex_of.get(a) == "F" and sex_of.get(b) != "F":
            a, b = b, a
        if (a, b) not in fam_children and (b, a) not in fam_children:
            fam_children[(a, b)]
    fam_ids = {key: f"F{i}" for i, key in
               enumerate(sorted(fam_children, key=lambda k: (k[0] or "", k[1] or "")), 1)}
    fams, famc = defaultdict(list), defaultdict(list)
    for key, children in fam_children.items():
        fid = fam_ids[key]
        for p in key:
            if p:
                fams[p].append(fid)
        for c in children:
            famc[c].append(fid)

    stamp = datetime.now(timezone.utc)
    out = []
    w = out.append
    w("0 HEAD")
    w("1 GEDC")
    w("2 VERS 7.0")
    w("1 SOUR ORDERLIFE")
    w("2 NAME The Gaiad genealogy - order.life")
    w("2 CORP Lifeism (命道教)")
    w("3 WWW https://order.life/")
    w(f"1 DATE {stamp.day} {MONTHS[stamp.month - 1]} {stamp.year}")
    w(f"2 TIME {stamp.strftime('%H:%M:%S')}Z")
    w("1 LANG en")
    w("1 SUBM @SUBM@")
    w("1 NOTE The synoptic ancestry of the Gaiad: Greek, Near Eastern, Egyptian, Trojan,")
    w("2 CONT Chinese, Mongol, Indian, Japanese and biblical lines integrated into a single descent.")
    w("2 CONT Every person carries a permanent UID, EXIDs (order.life and Wikidata), a REFN and a")
    w("2 CONT NOTE with the same IDs, so they can be matched back after any import.")
    w("0 @SUBM@ SUBM")
    w("1 NAME order.life")
    w("1 WWW https://order.life/")
    w("0 @S1@ SOUR")
    w("1 TITL The Gaiad genealogy (order.life)")
    w("1 AUTH Emma Leonhart")
    w("1 PUBL https://order.life/gaiad.ged")
    w("1 WWW https://order.life/")
    # The Gaiad itself, cited by chapter and stanza (Gaiad 132.5) for every person the entity resolution
    # (Gaiad/scripts/resolve_characters.py, regenerate_genealogy.py) tied to a tag in the verse.
    w("0 @S2@ SOUR")
    w("1 TITL The Gaiad")
    w("1 AUTH Emma Leonhart")
    w("1 PUBL https://order.life/gaiad/")
    w("1 WWW https://order.life/gaiad.pdf")

    canon = load_canonical_line()
    gaiad_cites = load_gaiad_citations()
    cladoplasts = defaultdict(list)
    clado_path = Path(__file__).resolve().parent.parent / "wikibase" / "analysis" / "cladoplasts.tsv"
    if clado_path.exists():
        import csv
        with open(clado_path, encoding="utf-8", newline="") as fh:
            for r in csv.DictReader(fh, delimiter="\t"):
                cladoplasts[r["qid"]].append((r["clade_wikidata"], r["clade_label"]))
    labels = defaultdict(list)
    labels_path = Path(__file__).resolve().parent.parent / "wikibase" / "analysis" / "labels.tsv"
    if labels_path.exists():
        import csv
        with open(labels_path, encoding="utf-8", newline="") as fh:
            for r in csv.DictReader(fh, delimiter="\t"):
                labels[r["qid"]].append((r["lang"], r["label"]))
    n_indi = n_trans = n_lineage = n_cite = n_cal = n_notes = n_clado = n_nk = 0
    for qid in sorted(persons, key=lambda q: int(q[1:]) if q[1:].isdigit() else 0):
        row = persons[qid]
        w(f"0 @I{qid}@ INDI")
        names = name_lines(row.get("label", ""), row.get("gedcom", "")) or [f"[{qid}]"]
        latin = [n for n in names if not lang_of(n)]
        other = [n for n in names if lang_of(n)]
        primary = latin[0] if latin else names[0]
        w(f"1 NAME {val(primary)}")
        for n in other:
            if n != primary:
                w(f"2 TRAN {val(n)}")
                w(f"3 LANG {lang_of(n)}")
                n_trans += 1
        # The item's own labels in the primary languages (zh, ja, ko; wikibase/analysis/labels.tsv), where
        # the name lines above do not already have them: as TRAN and as their own NAME, since programs
        # often drop TRAN.
        extra = [(lg, lb) for lg, lb in labels.get(qid, []) if lg in tran_langs and lb not in names]
        for lg, lb in extra:
            w(f"2 TRAN {val(lb)}")
            w(f"3 LANG {lg}")
            n_trans += 1
        for n in names:
            if n != primary:
                w(f"1 NAME {val(n)}")
                if lang_of(n):
                    w("2 TYPE OTHER")
                    w(f"3 PHRASE {lang_of(n)} name")
        for lg, lb in extra:
            w(f"1 NAME {val(lb)}")
            w("2 TYPE OTHER")
            w(f"3 PHRASE {lg} name")
        # Neo-kun'yomi (planning/neo-kunyomi-names.md; approved 2026-10-15): the root's kanji, read as the own name.
        g = given_name(row)
        kj = kanji_for(g) if qid not in cladoplasts else None   # a cladoplast's name is a clade's, not a given name
        if kj:
            w(f"1 NAME {kj}")
            w("2 TYPE OTHER")
            w(f"3 PHRASE neo-kun'yomi (read {val(g.split()[0])})")
            n_nk += 1
        more, lineage_notes = lineage_extras(qid, persons, sex_of, canon, labels)
        for n, phrase in lineage_names(qid, persons, sex_of, canon) + more:
            w(f"1 NAME {val(n)}")
            w("2 TYPE OTHER")
            w(f"3 PHRASE {phrase}")
            n_lineage += 1
        for note in lineage_notes:
            w(f"1 NOTE {val(note)}")
        w(f"1 SEX {sex_of[qid]}")

        prec_birth, prec_death = precision.get(qid, ("", ""))
        for tag, col, prec in (("BIRT", "birth", prec_birth), ("DEAT", "death", prec_death)):
            raw = (row.get(col) or "").strip()
            if not raw:
                continue
            date = ged7_date(raw, prec)
            if date:
                w(f"1 {tag}")
                w(f"2 DATE {date}")
                note = other_calendars(raw, prec)
                if note:
                    w(f"2 NOTE {val(note)}")
                    n_cal += 1
            else:
                w(f"1 {tag} Y")
                w(f"2 NOTE Date as recorded: {val(raw)}")

        for fid in famc[qid]:
            w(f"1 FAMC @{fid}@")
        for fid in fams[qid]:
            w(f"1 FAMS @{fid}@")

        uid = person_uid(qid)
        wd = (row.get("wikidata_qid") or "").strip()
        w(f"1 REFN {qid}")
        w("2 TYPE order.life")
        w(f"1 UID {uid}")
        w(f"1 EXID {qid}")
        w(f"2 TYPE {ORDERLIFE_QID_URI}")
        if wd:
            w(f"1 EXID {val(wd)}")
            w(f"2 TYPE {WIKIDATA_URI}")
        ids = f"order.life {qid}; UID {uid}" + (f"; Wikidata {wd}" if wd else "")
        w(f"1 NOTE Gaiad person {ids}")
        # Person notes (Emma, 2026-10-12: "a link to the order.life page on the individual, a link to their wiki
        # item if present, a link to ... their family search and or [Geni] items if present ... It'll cite verses").
        links = []
        if qid in PAGE_NAME and PAGE_NAME[qid]:
            slug = re.sub(r"[^a-zA-Z0-9_-]", "", PAGE_NAME[qid].replace(" ", "_")).lower()
            if slug:
                links.append(f"order.life https://order.life/gaiad/characters/{slug}/")
        if wd:
            links.append(f"Wikidata https://www.wikidata.org/wiki/{wd}")
        geni = (row.get("geni_id") or "").strip()
        if geni.isdigit():
            links.append(f"Geni https://www.geni.com/profile/index/{geni}")
        if links:
            w(f"1 NOTE Links: {'; '.join(links)}")
        # Cladoplasts: the clade this character personifies (wikibase P59), as a typed FACT, so the tree of life
        # and the family tree sit in one file (Emma, 2026-10-12: "some structured data related to cladoplasts").
        for clade, clabel in cladoplasts.get(qid, []):
            w(f"1 FACT {val(clabel or clade)}")
            w("2 TYPE Cladoplast of")
            w(f"2 NOTE Wikidata {clade}: https://www.wikidata.org/wiki/{clade}")
            n_clado += 1
        cites = gaiad_cites.get(qid, [])
        if cites:
            ch, st, _ = cites[0]
            k = len(cites)
            w(f"1 NOTE In the Gaiad: first named in chapter {ch} (Gaiad {ch}.{st}); cited in {k} stanza{'s' if k != 1 else ''}.")
            for lg, text in (("zh", f"在《盖亚德》中：首次出现于第{ch}章（Gaiad {ch}.{st}）；共有{k}节提及。"),
                             ("ja", f"『ガイアド』では：第{ch}章（Gaiad {ch}.{st}）に初出、{k}連で言及。"),
                             ("ko", f"《가이아드》에서: 제{ch}장(Gaiad {ch}.{st})에 처음 등장, {k}개 연에서 언급.")):
                w(f"2 TRAN {text}")
                w(f"3 LANG {lg}")
            n_notes += 1
        w("1 SOUR @S1@")
        w(f"2 PAGE order.life genealogy, {qid}")
        for ch, st, line in gaiad_cites.get(qid, []):
            w("1 SOUR @S2@")
            w(f"2 PAGE Gaiad {ch}.{st}")
            w("2 DATA")
            w(f"3 TEXT {val(line)}")
            w(f"2 NOTE https://order.life/gaiad/{ch:03d}/#s{st}")
            n_cite += 1
        n_indi += 1

    for key in sorted(fam_ids, key=lambda k: int(fam_ids[k][1:])):
        fid = fam_ids[key]
        husb, wife = key
        w(f"0 @{fid}@ FAM")
        if husb:
            w(f"1 HUSB @I{husb}@")
        if wife:
            w(f"1 WIFE @I{wife}@")
        for c in sorted(fam_children[key], key=lambda q: int(q[1:]) if q[1:].isdigit() else 0):
            w(f"1 CHIL @I{c}@")
        if husb and wife and frozenset((husb, wife)) in spouse_pairs:
            w("1 MARR Y")

    w("0 TRLR")
    w("")

    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    tmp = out_path.with_suffix(out_path.suffix + ".tmp")
    # utf-8-sig writes a byte-order mark, which GEDCOM 7 allows. Gramps 6.0 does not read 7.0,
    # falls back to its 5.5 reader and, with no BOM, decodes the file as cp1252: 16,572 of 17,199
    # non-ASCII names came out garbled in the 2026-10-15 round trip. With the BOM, none did.
    with open(tmp, "w", encoding="utf-8-sig", newline="\n") as f:
        f.write("\n".join(out))
    tmp.replace(out_path)
    return {"individuals": n_indi, "families": len(fam_ids), "translations": n_trans, "lineage_names": n_lineage, "gaiad_citations": n_cite, "calendar_notes": n_cal, "gaiad_notes": n_notes, "cladoplasts": n_clado, "neo_kunyomi": n_nk,
            "bytes": out_path.stat().st_size}


