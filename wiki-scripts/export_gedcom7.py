    w("1 AUTH Emma Leonhart")
    w("1 PUBL https://order.life/gaiad.ged")
    w("1 WWW https://order.life/")
    # The Gaiad itself, cited by chapter and stanza (Gaiad 132.5) for every person the entity resolution
    # (Gaiad/scripts/resolve_characters.py, regenerate_genealogy.py) tied to a tag in the verse.
    w("0 @S2@ SOUR")
    w("1 TITL The Gaiad")
    w("1 AUTH Emma Leonhart")
    w("1 PUBL https://order.life/gaiad/")
    w("1 WWW https://order.life/gaiad.pdf")

    canon = load_canonical_line()
    gaiad_cites = load_gaiad_citations()
    cladoplasts = defaultdict(list)
    clado_path = Path(__file__).resolve().parent.parent / "wikibase" / "analysis" / "cladoplasts.tsv"
    if clado_path.exists():
        import csv
        with open(clado_path, encoding="utf-8", newline="") as fh:
            for r in csv.DictReader(fh, delimiter="\t"):
                cladoplasts[r["qid"]].append((r["clade_wikidata"], r["clade_label"]))
    labels = defaultdict(list)
    labels_path = Path(__file__).resolve().parent.parent / "wikibase" / "analysis" / "labels.tsv"
    if labels_path.exists():
        import csv
        with open(labels_path, encoding="utf-8", newline="") as fh:
            for r in csv.DictReader(fh, delimiter="\t"):
                labels[r["qid"]].append((r["lang"], r["label"]))
    cjk = defaultdict(dict)
    cjk_path = labels_path.parent / "cjk_labels_verified.tsv"
    if cjk_path.exists():
        import csv
        with open(cjk_path, encoding="utf-8", newline="") as fh:
            for r in csv.DictReader(fh, delimiter="	"):
                cjk[r["qid"]].setdefault(r["lang"], r["label"])
    n_got = 0
    n_indi = n_trans = n_lineage = n_cite = n_cal = n_notes = n_clado = n_nk = n_zh = n_mon = n_read = 0
    readings = load_readings()
    temple_names, horus_names, abrahamic_names = build_monarch_names()
    zh_taken = {lb for v in labels.values() for lg, lb in v if lg == "zh"}
    for qid in sorted(persons, key=lambda q: int(q[1:]) if q[1:].isdigit() else 0):
        row = persons[qid]
        w(f"0 @I{qid}@ INDI")
        names = name_lines(row.get("label", ""), row.get("gedcom", "")) or [f"[{qid}]"]
        latin = [n for n in names if not lang_of(n)]
        other = [n for n in names if lang_of(n)]
        primary = latin[0] if latin else names[0]
        w(f"1 NAME {val(primary)}")
        for n in other:
            if n != primary:
                w(f"2 TRAN {val(n)}")
                w(f"3 LANG {lang_of(n)}")
                n_trans += 1
        # The item's own labels in the primary languages (zh, ja, ko; wikibase/analysis/labels.tsv), where
        # the name lines above do not already have them: as TRAN and as their own NAME, since programs
        # often drop TRAN.
        extra = [(lg, lb) for lg, lb in labels.get(qid, []) if lg in tran_langs and lb not in names]
        for lg, lb in extra:
            w(f"2 TRAN {val(lb)}")
            w(f"3 LANG {lg}")
            n_trans += 1
        own_zh = OWN_CHINESE.get(qid)
        if own_zh:   # her usual name in Chinese is her Chinese name, not a transliteration
            w(f"2 TRAN {own_zh[0]}{own_zh[1]}")
            w("3 LANG zh")
            n_trans += 1
        w("2 NOTE Usual name")
        for n in names:
            if n != primary:
                w(f"1 NAME {val(n)}")
                if lang_of(n):
                    w("2 TYPE OTHER")
                    w(f"3 PHRASE {lang_of(n)} name")
        for lg, lb in extra:
            w(f"1 NAME {val(lb)}")
            w("2 TYPE OTHER")
            w(f"3 PHRASE {lg} name")
        # Neo-kun'yomi (planning/neo-kunyomi-names.md; approved 2026-10-15): the root's kanji, read as the own name.
        g = given_name(row)
        kj = kanji_for(g) if qid not in cladoplasts else None   # a cladoplast's name is a clade's, not a given name
        if kj:
            w(f"1 NAME {kj}")
            w("2 TYPE OTHER")
            w(f"3 PHRASE neo-kun'yomi (read {val(g.split()[0])})")
            n_nk += 1
        # A Chinese name for those without a real one (planning/chinese-names.md; approved 2026-10-15): surname from
        # the family name's first syllable, given name from the own name's first syllables, unique in the file.
        # Written as its own name object (Emma, 2026-10-30): pinyin with the surname in slashes, the characters as
        # TRAN zh, labelled "Chinese name" (chinese_names.chinese_name_lines).
        if own_zh:
            for line in chinese_name_lines(*own_zh):
                w(line)
            n_zh += 1
        elif not any(lg == "zh" for lg, _ in labels.get(qid, [])) and qid not in cladoplasts and g:
            ged = clean_name(row.get("gedcom") or "")
            sur = ged.split("/")[1].strip() if ged.count("/") >= 2 else ""
            zh = chinese_name_parts(g, sur, zh_taken) if sur and not lang_of(g + sur) else None
            zh_lines = chinese_name_lines(*zh) if zh else []
            for line in zh_lines:
                w(line)
            n_zh += bool(zh_lines)
        # Temple and Horus names for monarchs (planning/monarch-names.md; approved 2026-10-15).
        if qid in temple_names:
            tn, why = temple_names[qid]
            w(f"1 NAME {tn}")
            w("2 TYPE OTHER")
            w(f"3 PHRASE temple name (generated; {val(why)})")
            n_mon += 1
        if qid in horus_names:
            hn, gloss, kind = horus_names[qid]
            w(f"1 NAME {hn}")
            w("2 TYPE OTHER")
            w(f"3 PHRASE Horus name ({kind}): {gloss}")
            n_mon += 1
        if qid in abrahamic_names:
            an, temple, why = abrahamic_names[qid]
            w(f"1 NAME {an}")
            w("2 TYPE OTHER")
            w(f"3 PHRASE Abrahamic name, from the temple name {val(temple)} ({val(why)})")
            n_mon += 1
        # Readings: the person's name transcribed into ja, zh and ko, word by word from the genealogy repo's curated
        # token table (wikibase/analysis/name_readings.tsv, copied from genealogy/reports/
        # garborg-name-transliterations.tsv; Emma, 2026-10-15: "Its ja/zh/ko readings"). A reading is not the person's
        # Chinese name (that is the schema name above) and overrides nothing: it is added only where the person has no
        # real label in that language.
        nm = (row.get("gedcom") or "").replace("/", " ").strip() or (row.get("label") or "").strip()
        toks = nm.split()
        if toks and qid not in cladoplasts and all(t in readings and readings[t][0] for t in toks):
            have = {lg for lg, _ in labels.get(qid, [])} | ({"zh"} if own_zh else set())
            for k, (lg, sep) in enumerate((("ja", "・"), ("zh", "·"), ("ko", " "))):
                parts = [readings[t][k] for t in toks]
                if lg not in have and all(parts):
                    w(f"1 NAME {sep.join(parts)}")
                    w("2 TYPE OTHER")
                    w(f"3 PHRASE {lg} reading (transcription, not a {'Chinese name' if lg == 'zh' else 'native name'})")
                    n_read += 1
        # Gothic script for everyone (Emma, 2026-10-25: "applying Gothic as a standard label thing"): the primary
        # Latin-script name, titles cut off, transliterated by gothic.py; reconstructed names for historical Goths.
        got = gothic.OVERRIDES.get(qid) or (gothic.gothic(gothic.name_part(primary)) if not lang_of(primary) else "")
        if got and re.search("[\U00010330-\U0001034F]", got) and got not in names:
            w(f"1 NAME {val(got)}")
            w("2 TYPE OTHER")
            w("3 PHRASE Gothic script (transliterated)" if qid not in gothic.OVERRIDES else "3 PHRASE Gothic name")
            n_got += 1
        more, lineage_notes = lineage_extras(qid, persons, sex_of, canon, labels, cjk)
        for n, phrase in lineage_names(qid, persons, sex_of, canon) + more:
            w(f"1 NAME {val(n)}")
            w("2 TYPE OTHER")
            w(f"3 PHRASE {phrase}")
            n_lineage += 1
        for note in lineage_notes:
            w(f"1 NOTE {val(note)}")
        w(f"1 SEX {sex_of[qid]}")

        prec_birth, prec_death = precision.get(qid, ("", ""))
        for tag, col, prec in (("BIRT", "birth", prec_birth), ("DEAT", "death", prec_death)):
            raw = (row.get(col) or "").strip()
            if not raw:
                continue
            if row.get("_synoptic"):
                # The synoptic tree's dates are GEDCOM dates already ("26 FEB 1996", "ABT 1700").
                if re.fullmatch(r"(ABT |BEF |AFT |EST |CAL )?(\d{1,2} )?([A-Z]{3} )?\d{1,4}( BCE)?", raw):
                    w(f"1 {tag}")
                    w(f"2 DATE {raw}")
                else:
                    w(f"1 {tag} Y")
                    w(f"2 NOTE Date as recorded: {val(raw)}")
                continue
            date = ged7_date(raw, prec)
            if date:
                w(f"1 {tag}")
                w(f"2 DATE {date}")
                note = other_calendars(raw, prec)
                if note:
                    w(f"2 NOTE {val(note)}")
                    n_cal += 1
            else:
                w(f"1 {tag} Y")
                w(f"2 NOTE Date as recorded: {val(raw)}")

        for fid in famc[qid]:
            w(f"1 FAMC @{fid}@")
        for fid in fams[qid]:
            w(f"1 FAMS @{fid}@")

        uid = person_uid(qid)
        wd = (row.get("wikidata_qid") or "").strip()
        syn = bool(row.get("_synoptic"))
        w(f"1 REFN {qid}")
        w("2 TYPE " + ("synoptic tree" if syn else "order.life"))
        w(f"1 UID {uid}")
        if not syn:
            w(f"1 EXID {qid}")
            w(f"2 TYPE {ORDERLIFE_QID_URI}")
        if wd:
            w(f"1 EXID {val(wd)}")
            w(f"2 TYPE {WIKIDATA_URI}")
        fs = (row.get("_fs") or "").strip()
        if fs:
            w(f"1 EXID {val(fs)}")
            w("2 TYPE https://www.familysearch.org/tree/person/details/")
        if syn:
            ids = f"synoptic tree {qid}; UID {uid}" + (f"; Wikidata {wd}" if wd else "") + (f"; FamilySearch {fs}" if fs else "")
            w(f"1 NOTE Ancestor from the synoptic tree: {ids}")
        else:
            ids = f"order.life {qid}; UID {uid}" + (f"; Wikidata {wd}" if wd else "")
            w(f"1 NOTE Gaiad person {ids}")
        # Person notes (Emma, 2026-10-12: "a link to the order.life page on the individual, a link to their wiki
        # item if present, a link to ... their family search and or [Geni] items if present ... It'll cite verses").
        links = []
        if qid in PAGE_NAME and PAGE_NAME[qid]:
            slug = re.sub(r"[^a-zA-Z0-9_-]", "", PAGE_NAME[qid].replace(" ", "_")).lower()
            if slug:
                links.append(f"order.life https://order.life/gaiad/characters/{slug}/")
        if wd:
            links.append(f"Wikidata https://www.wikidata.org/wiki/{wd}")
        geni = (row.get("geni_id") or "").strip()
        if geni.isdigit():
            links.append(f"Geni https://www.geni.com/profile/index/{geni}")
        if links:
            w(f"1 NOTE Links: {'; '.join(links)}")
        # Cladoplasts: the clade this character personifies (wikibase P59), as a typed FACT, so the tree of life
        # and the family tree sit in one file (Emma, 2026-10-12: "some structured data related to cladoplasts").
        for clade, clabel in cladoplasts.get(qid, []):
            w(f"1 FACT {val(clabel or clade)}")
            w("2 TYPE Cladoplast of")
            w(f"2 NOTE Wikidata {clade}: https://www.wikidata.org/wiki/{clade}")
            n_clado += 1
        cites = gaiad_cites.get(qid, [])
        if cites:
            ch, st, _ = cites[0]
            k = len(cites)
            w(f"1 NOTE In the Gaiad: first named in chapter {ch} (Gaiad {ch}.{st}); cited in {k} stanza{'s' if k != 1 else ''}.")
            for lg, text in (("zh", f"在《盖亚德》中：首次出现于第{ch}章（Gaiad {ch}.{st}）；共有{k}节提及。"),
                             ("ja", f"『ガイアド』では：第{ch}章（Gaiad {ch}.{st}）に初出、{k}連で言及。"),
                             ("ko", f"《가이아드》에서: 제{ch}장(Gaiad {ch}.{st})에 처음 등장, {k}개 연에서 언급.")):
                w(f"2 TRAN {text}")
                w(f"3 LANG {lg}")
            n_notes += 1
        w("1 SOUR @S1@")
        w(f"2 PAGE order.life genealogy, {qid}")
        for ch, st, line in gaiad_cites.get(qid, []):
            w("1 SOUR @S2@")
            w(f"2 PAGE Gaiad {ch}.{st}")
            w("2 DATA")
            w(f"3 TEXT {val(line)}")
            w(f"2 NOTE https://order.life/gaiad/{ch:03d}/#s{st}")
            n_cite += 1
        n_indi += 1

    for key in sorted(fam_ids, key=lambda k: int(fam_ids[k][1:])):
        fid = fam_ids[key]
        husb, wife = key
        w(f"0 @{fid}@ FAM")
        if husb:
            w(f"1 HUSB @I{husb}@")
        if wife:
            w(f"1 WIFE @I{wife}@")
        for c in sorted(fam_children[key], key=lambda q: int(q[1:]) if q[1:].isdigit() else 0):
            w(f"1 CHIL @I{c}@")
        if husb and wife and frozenset((husb, wife)) in spouse_pairs:
            w("1 MARR Y")

    w("0 TRLR")
    w("")

    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    tmp = out_path.with_suffix(out_path.suffix + ".tmp")
    # utf-8-sig writes a byte-order mark, which GEDCOM 7 allows. Gramps 6.0 does not read 7.0,
    # falls back to its 5.5 reader and, with no BOM, decodes the file as cp1252: 16,572 of 17,199
    # non-ASCII names came out garbled in the 2026-10-15 round trip. With the BOM, none did.
    with open(tmp, "w", encoding="utf-8-sig", newline="\n") as f:
        f.write("\n".join(out))
    tmp.replace(out_path)
    return {"individuals": n_indi, "families": len(fam_ids), "translations": n_trans, "lineage_names": n_lineage, "gaiad_citations": n_cite, "calendar_notes": n_cal, "gaiad_notes": n_notes, "cladoplasts": n_clado, "neo_kunyomi": n_nk, "chinese_names": n_zh, "monarch_names": n_mon, "readings": n_read, "gothic_names": n_got,
            "bytes": out_path.stat().st_size}


