def lineage_names(qid, persons, sex_of, canon):
    """The name schema's patronymic or matronymic (planning/name-schema.md), in the two forms
    Emma gave: English "Emma Helen's daughter" and Arabic "Emma bint Helen"."""
    if qid not in canon:
        return []
    parent, link = canon[qid]
    child_g, parent_g = given_name(persons[qid]), given_name(persons.get(parent, {}))
    if not child_g or not parent_g or parent_g.lower() in ("father", "mother"):
        return []
    # These two forms are Latin-script patterns; names in other scripts get their own forms
    # (Chinese, Japanese, Arabic script) in later steps of the schema.
    import unicodedata
    if any(ch.isalpha() and not unicodedata.name(ch, "").startswith("LATIN")
           for ch in unicodedata.normalize("NFD", child_g + parent_g)):
        return []
    kind = "patronymic" if link == "father" else "matronymic"
    rel = {"M": "son", "F": "daughter"}.get(sex_of.get(qid), "child")
    arabic = {"M": "ibn", "F": "bint"}.get(sex_of.get(qid), "ibn")
    return [(f"{child_g} {parent_g}'s {rel}", f"{kind}, English form"),
            (f"{child_g} {arabic} {parent_g}", f"{kind}, Arabic form")]

WELSH = re.compile(r"\b(ap|ab|ferch|verch)\s+(\S+)", re.I)
PLACEHOLDER_GIVEN = {"NN", "N.N.", "Unknown", "unknown", "?"}


def nasab_part(g):
    """A given name fit for a Latin-script nasab: not a placeholder, no ibn/bin/bint of its own, Latin script."""
    import unicodedata
    return bool(g) and g not in PLACEHOLDER_GIVEN and not re.search(r"\b(ibn|bin|bint)\b", g, re.I) and all(
        not ch.isalpha() or unicodedata.name(ch, "").startswith("LATIN") for ch in g)
RECORDED_PATRONYMIC = re.compile(r"\b(ap|ab|ferch|verch|ibn|bin|bint)\s+(\S+)", re.I)


def russian_patronymic(parent_given, sex):
    """A Russian patronymic from a parent's Russian given name, by the usual endings: -ович/-овна after a
    consonant, -евич/-евна for -й/-ь, -ич/-ична for -а/-я (Илья -> Ильич). An approximation, marked as such."""
    n = parent_given
    if not n or not re.fullmatch(r"[А-Яа-яЁё-]+", n):
        return ""
    if n[-1] in "йь":
        stem, m, f = n[:-1], "евич", "евна"
    elif n[-1] in "ая":
        stem, m, f = n[:-1], "ич", "ична"
    elif n[-1] in "еиоуыэю":
        stem, m, f = n, "вич", "вна"
    else:
        stem, m, f = n, "ович", "овна"
    return stem + (f if sex == "F" else m)


def lineage_extras(qid, persons, sex_of, canon, labels, cjk=None):
    """Name-schema step 2, later work (planning/name-schema.md): Welsh stacking where the record is Welsh-styled,
    Arabic-script and Russian forms where both person and parent have real labels in those languages, and a NOTE
    where the record's own patronymic differs from the canonical line. Returns (names, notes)."""
    names, notes = [], []
    if qid not in canon:
        return names, notes
    parent, link = canon[qid]
    kind = "patronymic" if link == "father" else "matronymic"
    sex = sex_of.get(qid)
    label = persons[qid].get("label") or ""
    def given(row):
        # Welsh-styled labels carry no separate given name: it is the word before the first ap/ferch.
        g = given_name(row)
        m = WELSH.search(row.get("label") or "")
        if not g and m:
            head = (row.get("label") or "")[:m.start()].strip()
            if head and " " not in head:
                g = head
        return g
    child_g, parent_g = given(persons[qid]), given(persons.get(parent, {}))
    if child_g and parent_g and parent_g.lower() not in ("father", "mother"):
        # Stacked where the record or its canonical parent is Welsh-styled (a Welsh line often names the
        # father in the Welsh way and the child by a single given name).
        if WELSH.search(label) or WELSH.search(persons.get(parent, {}).get("label") or ""):
            chain, cur, word = [child_g], parent, ("ferch" if sex == "F" else "ap")
            for _ in range(2):
                g = given(persons.get(cur, {}))
                if not g or g in PLACEHOLDER_GIVEN:
                    break
                if word == "ap" and g[0].lower() in "aeiouyâêîôûŵŷ":
                    word = "ab"  # Welsh writes ab before a vowel (ab Einion)
                chain.append(f"{word} {g}")
                word = "ap" if sex_of.get(cur) == "M" else "ferch"
                if cur not in canon:
                    break
                cur = canon[cur][0]
            if len(chain) > 2:
                names.append((" ".join(chain), f"{kind}, Welsh stacked form"))
        # Arabic nasab, stacked: where the record is itself written with ibn/bin/bint, the chain runs two
        # generations up the canonical line (Ali ibn Abi Talib ibn Abd al-Muttalib).
        if re.search(r"\b(ibn|bin|bint)\b", label, re.I) and nasab_part(child_g) and nasab_part(parent_g):
            chain, cur = [child_g, ("bint" if sex == "F" else "ibn"), parent_g], parent
            if cur in canon:
                g2 = given(persons.get(canon[cur][0], {}))
                if g2 and nasab_part(g2):
                    chain += ["bint" if sex_of.get(cur) == "F" else "ibn", g2]
            if len(chain) > 3:
                names.append((" ".join(chain), f"{kind}, Arabic stacked form (nasab)"))
        m = RECORDED_PATRONYMIC.search(label)
        if m and m.group(2).strip(",.").lower() != parent_g.split()[0].lower():
            notes.append(f"Recorded patronymic \"{m.group(0)}\"; by the canonical line to Aster and Andromeda, "
                         f"{child_g} is {parent_g}'s {'daughter' if sex == 'F' else 'son'}.")
    lab = dict(labels.get(qid, []))
    plab = dict(labels.get(parent, []))
    if lab.get("ar") and plab.get("ar"):
        word = "بنت" if sex == "F" else "بن"
        names.append((f"{lab['ar'].split()[0]} {word} {plab['ar'].split()[0]}", f"{kind}, Arabic script"))
    # Hebrew: X ben Y / X bat Y, from real Hebrew labels on both.
    if lab.get("he") and plab.get("he"):
        word = "בת" if sex == "F" else "בן"
        names.append((f"{lab['he'].split()[0]} {word} {plab['he'].split()[0]}", f"{kind}, Hebrew script"))
    # Georgian: X, Y's son (ძე) or daughter (ასული), the parent's name in the genitive (-ის, or -ს after a
    # vowel other than ი). Approximate, marked as such.
    if lab.get("ka") and plab.get("ka"):
        p = plab["ka"].split()[0]
        gen = p[:-1] + "ის" if p.endswith("ი") else p + "ს" if p[-1:] in "აეოუ" else p + "ის"
        word = "ასული" if sex == "F" else "ძე"
        names.append((f"{lab['ka'].split()[0]} {gen} {word}", f"{kind}, Georgian script (approximate)"))
    # Devanagari, the Sanskrit compound Y-putra X (दशरथपुत्र राम), -putrī for a daughter.
    if lab.get("hi") and plab.get("hi"):
        word = "पुत्री" if sex == "F" else "पुत्र"
        names.append((f"{plab['hi'].split()[0]}{word} {lab['hi'].split()[0]}", f"{kind}, Devanagari script"))
    # Russian form only where the person's own Russian label already carries a patronymic, so it is used
    # for people named in the Russian way, not imposed on a Japanese or Persian name.
    ru_has_pat = bool(lab.get("ru")) and bool(re.search(r"\S+(ович|евич|ич|овна|евна|ична|инична)\b", lab.get("ru", "")[len(lab.get("ru", "").split()[0]):]))
    first_ru = lab.get("ru", " ").split()[0] if lab.get("ru") else ""
    if first_ru.endswith(("ович", "евич", "овна", "евна", "ична")):
        ru_has_pat = False  # the record's first name is itself a patronymic (Igorevich Yaroslavich)
    if ru_has_pat and plab.get("ru"):
        pat = russian_patronymic(plab["ru"].split()[0], sex) if link == "father" else ""
        if pat:
            names.append((f"{lab['ru'].split()[0]} {pat}", f"{kind}, Russian form (approximate)"))
    # Chinese, Japanese and Korean: Y之子X / Y之女X, Yの子X / Yの娘X, Y의 아들 X / Y의 딸 X, from labels on both that
    # match the Wikidata item each record carries (cjk_labels_verified.tsv, verify_cjk_labels.py): copied labels
    # from the wrong item ("Arnhem-Nijmegen metropolitan area" on Iberian nobles) would otherwise go into them.
    # Whole labels, which in these languages are the name; any with spaces, brackets or Latin letters are skipped.
    if cjk:
        mine, theirs = cjk.get(qid, {}), cjk.get(parent, {})
        clean = lambda t: bool(t) and not re.search(r"[\sA-Za-z()（）\[\]［］,，、]", t)
        for lg, fmt, lang_name in (("zh", "{p}之{w}{c}", "Chinese"), ("ja", "{p}の{w}{c}", "Japanese"),
                                   ("ko", "{p}의 {w} {c}", "Korean")):
            c_, p_ = mine.get(lg), theirs.get(lg)
            if clean(c_) and clean(p_) and c_ != p_:
                word = {"zh": ("女", "子"), "ja": ("娘", "子"), "ko": ("딸", "아들")}[lg][0 if sex == "F" else 1]
                names.append((fmt.format(p=p_, w=word, c=c_), f"{kind}, {lang_name} form"))
    return names, notes


def build_gedcom7(out_path, extra_lang=None, graft="emma"):
    """extra_lang: a language directory's own language (Emma, 2026-10-14: the other language versions "only
    contain English, Japanese, Chinese, and then whatever ... other language the directory is in"); its real
    labels are added beside the primary zh, ja and ko."""
    tran_langs = PRIMARY_LANGS + ((extra_lang,) if extra_lang and extra_lang not in PRIMARY_LANGS else ())
    persons, parents_of, spouse_pairs, precision = load()
    graft_synoptic(persons, parents_of, graft)

    sex_of = {}
    for qid, row in persons.items():
        raw = row.get("sex") or ""
        sex_of[qid] = "M" if raw == SEX_MALE else "F" if raw == SEX_FEMALE else "U"

    fam_children = defaultdict(set)
    for child, parents in parents_of.items():
        for key in couples_for_child(parents, sex_of, spouse_pairs):
            fam_children[key].add(child)
    for pair in spouse_pairs:
        a, b = sorted(pair)
        if sex_of.get(a) == "F" and sex_of.get(b) != "F":
            a, b = b, a
        if (a, b) not in fam_children and (b, a) not in fam_children:
            fam_children[(a, b)]
    fam_ids = {key: f"F{i}" for i, key in
               enumerate(sorted(fam_children, key=lambda k: (k[0] or "", k[1] or "")), 1)}
    fams, famc = defaultdict(list), defaultdict(list)
    for key, children in fam_children.items():
        fid = fam_ids[key]
        for p in key:
            if p:
                fams[p].append(fid)
        for c in children:
            famc[c].append(fid)

    stamp = datetime.now(timezone.utc)
    out = []
    w = out.append
    w("0 HEAD")
    w("1 GEDC")
    w("2 VERS 7.0")
    w("1 SOUR ORDERLIFE")
