CJK_RE = re.compile(r"[぀-ヿ]")          # kana: Japanese
HAN_RE = re.compile(r"[一-鿿]")
HANGUL_RE = re.compile(r"[가-힯]")
CYRILLIC_RE = re.compile(r"[Ѐ-ӿ]")
ARABIC_RE = re.compile(r"[؀-ۿ]")
DEVANAGARI_RE = re.compile(r"[ऀ-ॿ]")
GREEK_RE = re.compile(r"[Ͱ-Ͽ]")


def lang_of(name):
    """A BCP 47 tag for a name written in a non-Latin script, or None for Latin script."""
    if CJK_RE.search(name):
        return "ja"
    if HANGUL_RE.search(name):
        return "ko"
    if HAN_RE.search(name):
        return "zh"
    if CYRILLIC_RE.search(name):
        return "ru"
    if ARABIC_RE.search(name):
        return "ar"
    if DEVANAGARI_RE.search(name):
        return "hi"
    if GREEK_RE.search(name):
        return "el"
    return None


def val(text):
    """GEDCOM 7 doubles an @ only at the start of a line value."""
    text = " ".join((text or "").split())
    return "@" + text if text.startswith("@") else text


def ged7_date(raw, precision=None):
    """Wikidata-style timestamp -> a GEDCOM 7 DATE. GEDCOM 7 years are unbounded integers, so
    deep time (Aster's -13000000000) is representable as '13000000000 BCE'."""
    if not raw:
        return None
    s = raw.strip()
    neg = s.startswith("-")
    if s[0] in "+-":
        s = s[1:]
    bits = s.split("T", 1)[0].split("-")
    if not bits or not bits[0].isdigit():
        return None
    year = int(bits[0])
    if year == 0:
        return None
    month = int(bits[1]) if len(bits) > 1 and bits[1].isdigit() else 0
    day = int(bits[2]) if len(bits) > 2 and bits[2].isdigit() else 0
    try:
        prec = int(precision) if precision not in (None, "") else 11
    except (TypeError, ValueError):
        prec = 11
    if prec < 10:
        month = day = 0
    elif prec == 10:
        day = 0
    out = []
    if 1 <= month <= 12:
        if 1 <= day <= 31:
            out.append(str(day))
        out.append(MONTHS[month - 1])
    out.append(str(year))
    if neg:
        out.append("BCE")
    date = " ".join(out)
    return f"ABT {date}" if prec <= 8 else date


def other_calendars(raw, precision=None):
    """For an exact date (day precision), its Gaian, Hebrew, Islamic and solar Hijri dates (calendars.py)."""
    try:
        prec = int(precision) if precision not in (None, "") else 11
    except (TypeError, ValueError):
        prec = 11
    if prec < 11:
        return None
    s = raw.strip()
    neg = s.startswith("-")
    bits = s.lstrip("+-").split("T", 1)[0].split("-")
    if len(bits) < 3 or not all(x.isdigit() for x in bits[:3]):
        return None
    y, m, d = int(bits[0]), int(bits[1]), int(bits[2])
    if y == 0 or not (1 <= m <= 12 and 1 <= d <= 31):
        return None
    from calendars import calendar_note
    return calendar_note(1 - y if neg else y, m, d)   # BCE year n is astronomical 1 - n


