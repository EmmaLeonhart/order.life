"""
Export the whole Gaiad genealogy as a GEDCOM 7 file, served at https://order.life/gaiad.ged.

Emma, 2026-10-12: Gaiad.ged in GEDCOM 7, "canonical enough it should be generated by CI/CD",
and idiot-proofed "so that entity resolution is preserved even when programs throw a lot out".
So every person carries the same identity redundantly, in the places programs drop least:

  UID   a permanent UUID (UUIDv5 of the person's order.life QID, so it never changes)
  EXID  the order.life QID and the Wikidata QID, each with its type URI
  REFN  the order.life QID
  NOTE  the same IDs in plain text
  SOUR  a citation of the order.life genealogy naming the QID

Names in another script are also given as TRAN with LANG under the primary NAME, and kept as
their own NAME line too, since many programs drop TRAN. Same data as export_gedcom.py (the
GEDCOM 5.5.1 file at /gedcom/gaiad.ged); this module reuses its loading and family logic.

Run standalone:  python wiki-scripts/export_gedcom7.py [out.ged]
"""
import re
import sys
import uuid
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from export_gedcom import (ANA, MONTHS, SEX_FEMALE, SEX_MALE, clean_name, couples_for_child,
                           load, name_lines)

ORDERLIFE_QID_URI = "https://order.life/wikibase/entity/"
WIKIDATA_URI = "http://www.wikidata.org/entity/"
# Fixed namespace: the UID of a person is uuid5(UID_NAMESPACE, their order.life QID) forever.
UID_NAMESPACE = uuid.uuid5(uuid.NAMESPACE_URL, "https://order.life/gaiad/person/")

CJK_RE = re.compile(r"[぀-ヿ]")          # kana: Japanese
HAN_RE = re.compile(r"[一-鿿]")
HANGUL_RE = re.compile(r"[가-힯]")
CYRILLIC_RE = re.compile(r"[Ѐ-ӿ]")
ARABIC_RE = re.compile(r"[؀-ۿ]")
DEVANAGARI_RE = re.compile(r"[ऀ-ॿ]")
GREEK_RE = re.compile(r"[Ͱ-Ͽ]")


def lang_of(name):
    """A BCP 47 tag for a name written in a non-Latin script, or None for Latin script."""
    if CJK_RE.search(name):
        return "ja"
    if HANGUL_RE.search(name):
        return "ko"
    if HAN_RE.search(name):
        return "zh"
    if CYRILLIC_RE.search(name):
        return "ru"
    if ARABIC_RE.search(name):
        return "ar"
    if DEVANAGARI_RE.search(name):
        return "hi"
    if GREEK_RE.search(name):
        return "el"
    return None


def val(text):
    """GEDCOM 7 doubles an @ only at the start of a line value."""
    text = " ".join((text or "").split())
    return "@" + text if text.startswith("@") else text


def ged7_date(raw, precision=None):
    """Wikidata-style timestamp -> a GEDCOM 7 DATE. GEDCOM 7 years are unbounded integers, so
    deep time (Aster's -13000000000) is representable as '13000000000 BCE'."""
    if not raw:
        return None
    s = raw.strip()
    neg = s.startswith("-")
    if s[0] in "+-":
        s = s[1:]
    bits = s.split("T", 1)[0].split("-")
    if not bits or not bits[0].isdigit():
        return None
    year = int(bits[0])
    if year == 0:
        return None
    month = int(bits[1]) if len(bits) > 1 and bits[1].isdigit() else 0
    day = int(bits[2]) if len(bits) > 2 and bits[2].isdigit() else 0
    try:
        prec = int(precision) if precision not in (None, "") else 11
    except (TypeError, ValueError):
        prec = 11
    if prec < 10:
        month = day = 0
    elif prec == 10:
        day = 0
    out = []
    if 1 <= month <= 12:
        if 1 <= day <= 31:
            out.append(str(day))
        out.append(MONTHS[month - 1])
    out.append(str(year))
    if neg:
        out.append("BCE")
    date = " ".join(out)
    return f"ABT {date}" if prec <= 8 else date


def person_uid(qid):
    return str(uuid.uuid5(UID_NAMESPACE, qid))


def build_gedcom7(out_path):
    persons, parents_of, spouse_pairs, precision = load()

    sex_of = {}
    for qid, row in persons.items():
        raw = row.get("sex") or ""
        sex_of[qid] = "M" if raw == SEX_MALE else "F" if raw == SEX_FEMALE else "U"

    fam_children = defaultdict(set)
    for child, parents in parents_of.items():
        for key in couples_for_child(parents, sex_of, spouse_pairs):
            fam_children[key].add(child)
    for pair in spouse_pairs:
        a, b = sorted(pair)
        if sex_of.get(a) == "F" and sex_of.get(b) != "F":
            a, b = b, a
        if (a, b) not in fam_children and (b, a) not in fam_children:
            fam_children[(a, b)]
    fam_ids = {key: f"F{i}" for i, key in
               enumerate(sorted(fam_children, key=lambda k: (k[0] or "", k[1] or "")), 1)}
    fams, famc = defaultdict(list), defaultdict(list)
    for key, children in fam_children.items():
        fid = fam_ids[key]
        for p in key:
            if p:
                fams[p].append(fid)
        for c in children:
            famc[c].append(fid)

    stamp = datetime.now(timezone.utc)
    out = []
    w = out.append
    w("0 HEAD")
    w("1 GEDC")
    w("2 VERS 7.0")
    w("1 SOUR ORDERLIFE")
    w("2 NAME The Gaiad genealogy - order.life")
    w("2 CORP Lifeism (命道教)")
    w("3 WWW https://order.life/")
    w(f"1 DATE {stamp.day} {MONTHS[stamp.month - 1]} {stamp.year}")
    w(f"2 TIME {stamp.strftime('%H:%M:%S')}Z")
    w("1 LANG en")
    w("1 SUBM @SUBM@")
    w("1 NOTE The synoptic ancestry of the Gaiad: Greek, Near Eastern, Egyptian, Trojan,")
    w("2 CONT Chinese, Mongol, Indian, Japanese and biblical lines integrated into a single descent.")
    w("2 CONT Every person carries a permanent UID, EXIDs (order.life and Wikidata), a REFN and a")
    w("2 CONT NOTE with the same IDs, so they can be matched back after any import.")
    w("0 @SUBM@ SUBM")
    w("1 NAME order.life")
    w("1 WWW https://order.life/")
    w("0 @S1@ SOUR")
    w("1 TITL The Gaiad genealogy (order.life)")
    w("1 AUTH Emma Leonhart")
    w("1 PUBL https://order.life/gaiad.ged")
    w("1 WWW https://order.life/")

    n_indi = n_trans = 0
    for qid in sorted(persons, key=lambda q: int(q[1:]) if q[1:].isdigit() else 0):
        row = persons[qid]
        w(f"0 @I{qid}@ INDI")
        names = name_lines(row.get("label", ""), row.get("gedcom", "")) or [f"[{qid}]"]
        latin = [n for n in names if not lang_of(n)]
        other = [n for n in names if lang_of(n)]
        primary = latin[0] if latin else names[0]
        w(f"1 NAME {val(primary)}")
        for n in other:
            if n != primary:
                w(f"2 TRAN {val(n)}")
                w(f"3 LANG {lang_of(n)}")
                n_trans += 1
        for n in names:
            if n != primary:
                w(f"1 NAME {val(n)}")
                if lang_of(n):
                    w("2 TYPE OTHER")
                    w(f"3 PHRASE {lang_of(n)} name")
        w(f"1 SEX {sex_of[qid]}")

        prec_birth, prec_death = precision.get(qid, ("", ""))
        for tag, col, prec in (("BIRT", "birth", prec_birth), ("DEAT", "death", prec_death)):
            raw = (row.get(col) or "").strip()
            if not raw:
                continue
            date = ged7_date(raw, prec)
            if date:
                w(f"1 {tag}")
                w(f"2 DATE {date}")
            else:
                w(f"1 {tag} Y")
                w(f"2 NOTE Date as recorded: {val(raw)}")

        for fid in famc[qid]:
            w(f"1 FAMC @{fid}@")
        for fid in fams[qid]:
            w(f"1 FAMS @{fid}@")

        uid = person_uid(qid)
        wd = (row.get("wikidata_qid") or "").strip()
        w(f"1 REFN {qid}")
        w("2 TYPE order.life")
        w(f"1 UID {uid}")
        w(f"1 EXID {qid}")
        w(f"2 TYPE {ORDERLIFE_QID_URI}")
        if wd:
            w(f"1 EXID {val(wd)}")
            w(f"2 TYPE {WIKIDATA_URI}")
        ids = f"order.life {qid}; UID {uid}" + (f"; Wikidata {wd}" if wd else "")
        w(f"1 NOTE Gaiad person {ids}")
        w("1 SOUR @S1@")
        w(f"2 PAGE order.life genealogy, {qid}")
        n_indi += 1

    for key in sorted(fam_ids, key=lambda k: int(fam_ids[k][1:])):
        fid = fam_ids[key]
        husb, wife = key
        w(f"0 @{fid}@ FAM")
        if husb:
            w(f"1 HUSB @I{husb}@")
        if wife:
            w(f"1 WIFE @I{wife}@")
        for c in sorted(fam_children[key], key=lambda q: int(q[1:]) if q[1:].isdigit() else 0):
            w(f"1 CHIL @I{c}@")
        if husb and wife and frozenset((husb, wife)) in spouse_pairs:
            w("1 MARR Y")

    w("0 TRLR")
    w("")

    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    tmp = out_path.with_suffix(out_path.suffix + ".tmp")
    with open(tmp, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    tmp.replace(out_path)
    return {"individuals": n_indi, "families": len(fam_ids), "translations": n_trans,
            "bytes": out_path.stat().st_size}


if __name__ == "__main__":
    dest = Path(sys.argv[1]) if len(sys.argv) > 1 else ANA / "gaiad7.ged"
    stats = build_gedcom7(dest)
    print(f"Wrote {dest}")
    for k, v in stats.items():
        print(f"  {k}: {v:,}")
